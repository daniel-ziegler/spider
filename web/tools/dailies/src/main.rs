//! Picks the daily challenges: for every date in a range and each of 1, 2
//! and 4 suits, the first candidate deal that the solver proves winnable.
//! Candidates come from a hash of the date, so a rerun picks the same deals.
//! Dates already in the file are kept as they are.
//!
//! Usage: cargo run --release -- FIRST_DATE LAST_DATE [FILE]
//! (FILE defaults to ../../challenges.txt; lines are `date suits seed`).

use chrono::NaiveDate;
use spider::game::Game;
use spider::solver::{Solver, Verdict};
use std::collections::BTreeMap;
use std::sync::atomic::{AtomicUsize, Ordering};

const SUITS: [u8; 3] = [1, 2, 4];
const BUDGET: u64 = 3_000_000;

fn splitmix(mut z: u64) -> u64 {
    z = z.wrapping_add(0x9E3779B97F4A7C15);
    z = (z ^ (z >> 30)).wrapping_mul(0xBF58476D1CE4E5B9);
    z = (z ^ (z >> 27)).wrapping_mul(0x94D049BB133111EB);
    z ^ (z >> 31)
}

/// The k-th candidate deal for a date: a seed of at most nine digits.
fn candidate(date: NaiveDate, suits: u8, k: u64) -> u64 {
    let day = date.format("%Y%m%d").to_string().parse::<u64>().unwrap();
    1 + splitmix((day << 16) | ((suits as u64) << 8) | k) % 999_999_999
}

fn pick(date: NaiveDate, suits: u8) -> u64 {
    (0..)
        .map(|k| candidate(date, suits, k))
        .find(|&seed| {
            let g = Game::new(suits, seed);
            Solver::new(&g, BUDGET).solve(&g).verdict == Verdict::Solvable
        })
        .unwrap()
}

fn main() {
    let a: Vec<String> = std::env::args().collect();
    if a.len() < 3 {
        eprintln!("usage: dailies FIRST_DATE LAST_DATE [FILE]");
        std::process::exit(2);
    }
    let first: NaiveDate = a[1].parse().expect("FIRST_DATE as YYYY-MM-DD");
    let last: NaiveDate = a[2].parse().expect("LAST_DATE as YYYY-MM-DD");
    let path = a.get(3).cloned().unwrap_or_else(|| "../../challenges.txt".into());

    let mut picks: BTreeMap<(NaiveDate, u8), u64> = BTreeMap::new();
    let text = std::fs::read_to_string(&path).unwrap_or_default();
    for line in text.lines().filter(|l| !l.starts_with('#') && !l.trim().is_empty()) {
        let f: Vec<&str> = line.split_whitespace().collect();
        picks.insert((f[0].parse().unwrap(), f[1].parse().unwrap()), f[2].parse().unwrap());
    }

    let todo: Vec<(NaiveDate, u8)> = first
        .iter_days()
        .take_while(|d| *d <= last)
        .flat_map(|d| SUITS.map(|s| (d, s)))
        .filter(|key| !picks.contains_key(key))
        .collect();
    let next = AtomicUsize::new(0);
    let threads = std::thread::available_parallelism().map_or(4, |n| n.get());
    let found: Vec<((NaiveDate, u8), u64)> = std::thread::scope(|s| {
        let workers: Vec<_> = (0..threads)
            .map(|_| {
                s.spawn(|| {
                    let mut out = Vec::new();
                    loop {
                        let i = next.fetch_add(1, Ordering::Relaxed);
                        let Some(&(date, suits)) = todo.get(i) else { break };
                        out.push(((date, suits), pick(date, suits)));
                        if i % 50 == 0 {
                            eprintln!("{i}/{}", todo.len());
                        }
                    }
                    out
                })
            })
            .collect();
        workers.into_iter().flat_map(|w| w.join().unwrap()).collect()
    });
    picks.extend(found);

    // The file's own comments are kept.
    let mut out: String = text.lines().filter(|l| l.starts_with('#')).map(|l| format!("{l}\n")).collect();
    if out.is_empty() {
        out.push_str("# Daily challenges: date suits seed. Generated by web/tools/dailies; every deal is solver-verified winnable.\n");
    }
    for ((date, suits), seed) in &picks {
        out.push_str(&format!("{date} {suits} {seed}\n"));
    }
    std::fs::write(&path, out).unwrap();
    eprintln!("{} challenges in {path}", picks.len());
}
