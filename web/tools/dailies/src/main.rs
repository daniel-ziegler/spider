//! Picks the daily challenges: for every date in a range and each of 1, 2,
//! 3 and 4 suits, the first candidate deal that the solver proves winnable.
//! Candidates come from a hash of the date, so a rerun picks the same deals.
//! Dates already in the file are kept as they are.
//!
//! Usage: cargo run --release -- FIRST_DATE LAST_DATE [FILE]
//! (FILE defaults to ../../challenges.txt; lines are `date suits seed`).
//!
//! `cargo run --release -- medium FIRST_DATE LAST_DATE [FILE]` (FILE
//! defaults to ../../medium-challenges.txt, in the same format) picks the
//! medium challenges instead, for three and four suits: for each date in
//! turn the next medium deal (see [`WEAK`]) of medium3.txt or medium4.txt,
//! in a shuffled order that depends only on the seeds, that the web game's
//! computer wins (computer3.txt, computer4.txt, which `medium.sh` writes) and
//! that is no challenge yet, of either kind. Run it in this directory; to
//! pick days again, as when the computer has changed, run `medium.sh`.

use chrono::NaiveDate;
use spider::game::Game;
use spider::solver::{Solver, Verdict};
use std::collections::BTreeMap;
use std::sync::atomic::{AtomicUsize, Ordering};

const SUITS: [u8; 4] = [1, 2, 3, 4];
const BUDGET: u64 = 3_000_000;

fn splitmix(mut z: u64) -> u64 {
    z = z.wrapping_add(0x9E3779B97F4A7C15);
    z = (z ^ (z >> 30)).wrapping_mul(0xBF58476D1CE4E5B9);
    z = (z ^ (z >> 27)).wrapping_mul(0x94D049BB133111EB);
    z ^ (z >> 31)
}

/// The k-th candidate deal for a date: a seed of at most nine digits.
fn candidate(date: NaiveDate, suits: u8, k: u64) -> u64 {
    let day = date.format("%Y%m%d").to_string().parse::<u64>().unwrap();
    1 + splitmix((day << 16) | ((suits as u64) << 8) | k) % 999_999_999
}

fn pick(date: NaiveDate, suits: u8) -> u64 {
    (0..)
        .map(|k| candidate(date, suits, k))
        .find(|&seed| {
            let g = Game::new(suits, seed);
            Solver::new(&g, BUDGET).solve(&g).verdict == Verdict::Solvable
        })
        .unwrap()
}

/// `date suits seed` lines, comments aside.
fn read(text: &str) -> BTreeMap<(NaiveDate, u8), u64> {
    text.lines()
        .filter(|l| !l.starts_with('#') && !l.trim().is_empty())
        .map(|line| {
            let f: Vec<&str> = line.split_whitespace().collect();
            ((f[0].parse().unwrap(), f[1].parse().unwrap()), f[2].parse().unwrap())
        })
        .collect()
}

/// The file again: its own comments (or `header`), then the picks.
fn write(path: &str, text: &str, header: &str, picks: &BTreeMap<(NaiveDate, u8), u64>) {
    let mut out: String = text.lines().filter(|l| l.starts_with('#')).map(|l| format!("{l}\n")).collect();
    if out.is_empty() {
        out.push_str(header);
    }
    for ((date, suits), seed) in picks {
        out.push_str(&format!("{date} {suits} {seed}\n"));
    }
    std::fs::write(path, out).unwrap();
    eprintln!("{} challenges in {path}", picks.len());
}

const MEDIUM_HEADER: &str = "# Medium daily challenges (three and four suits): date suits seed. Generated by web/tools/dailies medium:\n\
# through 2026-11-10 from tools/dailies/picked3_medium.txt and picked4_medium.txt, then from medium3.txt and medium4.txt.\n";

/// The medium deals among the graded seeds of medium3.txt and medium4.txt
/// (lines of `../../../src/bin/medium_rates.rs`): those of whose 300 games
/// (`weak` and `again`) the weak player wins a share within `WEAK` (three
/// suits, four suits), and that the computer, wavering, wins at least `SHIP`
/// of 30 times.
const WEAK: [std::ops::RangeInclusive<f64>; 2] = [0.60..=0.70, 0.57..=0.67];
const SHIP: u32 = 27;

/// `name a/n` (or `name a`) of a line of rates: (a, n).
fn rate(line: &str, name: &str) -> (u32, u32) {
    let mut f = line.split_whitespace().skip_while(|w| *w != name);
    let v = f.nth(1).unwrap_or_else(|| panic!("no {name} in {line}"));
    let mut v = v.split('/').map(|x| x.parse().unwrap_or_else(|_| panic!("{name} in {line}")));
    (v.next().unwrap(), v.next().unwrap_or(1))
}

fn medium(a: &[String]) {
    let first: NaiveDate = a[0].parse().expect("FIRST_DATE as YYYY-MM-DD");
    let last: NaiveDate = a[1].parse().expect("LAST_DATE as YYYY-MM-DD");
    let path = a.get(2).cloned().unwrap_or_else(|| "../../medium-challenges.txt".into());
    let text = std::fs::read_to_string(&path).unwrap_or_default();
    let mut picks = read(&text);
    let hard = read(&std::fs::read_to_string("../../challenges.txt").expect("../../challenges.txt"));
    for suits in [3u8, 4] {
        let (file, played) = (format!("medium{suits}.txt"), format!("computer{suits}.txt"));
        // The seeds whose game the computer wins, as the web game plays it (computer.mjs).
        let won: std::collections::HashMap<u64, bool> = std::fs::read_to_string(&played)
            .unwrap_or_else(|_| panic!("{played}: run medium.sh"))
            .lines()
            .map(|l| (rate(l, "seed").0 as u64, rate(l, "won").0 == 1))
            .collect();
        let i = suits as usize - 3;
        let mut seeds: Vec<u64> = std::fs::read_to_string(&file)
            .expect(&file)
            .lines()
            .filter(|l| !l.starts_with('#') && !l.trim().is_empty())
            .filter(|l| {
                let ((w, n), (again, more)) = (rate(l, "weak"), rate(l, "again"));
                WEAK[i].contains(&((w + again) as f64 / (n + more) as f64)) && rate(l, "ship").0 >= SHIP
            })
            .map(|l| rate(l, "seed").0 as u64)
            .collect();
        let graded = seeds.len();
        seeds.retain(|seed| *won.get(seed).unwrap_or_else(|| panic!("seed {seed} is not in {played}: run medium.sh")));
        eprintln!("{suits} suits: {graded} seeds of {file} are medium, and the computer wins {} of them", seeds.len());
        seeds.sort_by_key(|&seed| (splitmix(seed ^ ((suits as u64) << 56)), seed));
        let used: std::collections::HashSet<u64> = picks.iter().chain(&hard).filter(|(k, _)| k.1 == suits).map(|(_, &seed)| seed).collect();
        let mut free = seeds.into_iter().filter(|seed| !used.contains(seed));
        for date in first.iter_days().take_while(|d| *d <= last) {
            if !picks.contains_key(&(date, suits)) {
                picks.insert((date, suits), free.next().unwrap_or_else(|| panic!("{file} has run out at {date}")));
            }
        }
        eprintln!("{suits} suits: {} of them left", free.count());
    }
    write(&path, &text, MEDIUM_HEADER, &picks);
}

fn main() {
    let a: Vec<String> = std::env::args().collect();
    if a.get(1).is_some_and(|m| m == "medium") && a.len() >= 4 {
        return medium(&a[2..]);
    }
    if a.len() < 3 {
        eprintln!("usage: dailies [medium] FIRST_DATE LAST_DATE [FILE]");
        std::process::exit(2);
    }
    let first: NaiveDate = a[1].parse().expect("FIRST_DATE as YYYY-MM-DD");
    let last: NaiveDate = a[2].parse().expect("LAST_DATE as YYYY-MM-DD");
    let path = a.get(3).cloned().unwrap_or_else(|| "../../challenges.txt".into());

    let text = std::fs::read_to_string(&path).unwrap_or_default();
    let mut picks = read(&text);

    let todo: Vec<(NaiveDate, u8)> = first
        .iter_days()
        .take_while(|d| *d <= last)
        .flat_map(|d| SUITS.map(|s| (d, s)))
        .filter(|key| !picks.contains_key(key))
        .collect();
    let next = AtomicUsize::new(0);
    let threads = std::thread::available_parallelism().map_or(4, |n| n.get());
    let found: Vec<((NaiveDate, u8), u64)> = std::thread::scope(|s| {
        let workers: Vec<_> = (0..threads)
            .map(|_| {
                s.spawn(|| {
                    let mut out = Vec::new();
                    loop {
                        let i = next.fetch_add(1, Ordering::Relaxed);
                        let Some(&(date, suits)) = todo.get(i) else { break };
                        out.push(((date, suits), pick(date, suits)));
                        if i % 50 == 0 {
                            eprintln!("{i}/{}", todo.len());
                        }
                    }
                    out
                })
            })
            .collect();
        workers.into_iter().flat_map(|w| w.join().unwrap()).collect()
    });
    picks.extend(found);

    // The file's own comments are kept.
    write(&path, &text, "# Daily challenges: date suits seed. Generated by web/tools/dailies; every deal is solver-verified winnable.\n", &picks);
}
