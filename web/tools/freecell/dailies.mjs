// Picks FreeCell's daily challenges into ../../freecell-challenges.txt
// ("date deal" lines): for each date FROM..TO not in the file yet, the first
// of the date's candidates (deals 1-1,000,000 from a hash of the date) that
// no other day has, that can be won (static/fcwinnable.js finds a line), and
// that is not easy: the dumb player (dumb.mjs) wins at most MAX of GAMES
// games of it. Dates in the file are kept, so extending it never changes a
// past challenge.
//   node tools/freecell/dailies.mjs 2028-01-01 2028-12-31
import { readFileSync, writeFileSync } from 'node:fs';
import { FreeCell } from '../../static/freecell.js';
import { solve } from '../../static/fcwinnable.js';
import { winRate } from './dumb.mjs';

const MAX = 0.1, GAMES = 40, DEALS = 1_000_000;
const FILE = new URL('../../freecell-challenges.txt', import.meta.url);
const HEADER = `# FreeCell's daily challenges: date deal. Generated by web/tools/freecell/dailies.mjs; every deal can be won,
# and the dumb player (tools/freecell/dumb.mjs) wins at most ${MAX * 100}% of its games of it.
`;

const [from, to] = process.argv.slice(2);
if (!/^\d{4}-\d\d-\d\d$/.test(from) || !/^\d{4}-\d\d-\d\d$/.test(to)) {
  console.error('usage: node tools/freecell/dailies.mjs FROM-DATE TO-DATE');
  process.exit(1);
}

const picked = new Map(); // date -> deal
try {
  for (const line of readFileSync(FILE, 'utf8').split('\n')) {
    if (line && !line.startsWith('#')) picked.set(line.split(' ')[0], +line.split(' ')[1]);
  }
} catch { /* no file yet */ }
const used = new Set(picked.values());

// The date's i-th candidate (FNV-1a of "date/i").
function candidate(date, i) {
  let h = 0x811c9dc5;
  for (const ch of `${date}/${i}`) h = Math.imul(h ^ ch.charCodeAt(0), 0x01000193);
  return 1 + (h >>> 0) % DEALS;
}

function hard(deal) {
  const rate = winRate(deal, GAMES);
  if (rate > MAX) return false;
  const g = new FreeCell(deal);
  return rate > 0 || solve(g.columns, g.cells, 2_000_000).verdict === 'won';
}

let tried = 0, added = 0;
for (let day = new Date(`${from}T00:00Z`); day <= new Date(`${to}T00:00Z`); day.setUTCDate(day.getUTCDate() + 1)) {
  const date = day.toISOString().slice(0, 10);
  if (picked.has(date)) continue;
  for (let i = 0; ; i++) {
    const deal = candidate(date, i);
    tried++;
    if (used.has(deal) || !hard(deal)) continue;
    picked.set(date, deal);
    used.add(deal);
    added++;
    break;
  }
}
writeFileSync(FILE, HEADER + [...picked].sort().map(([date, deal]) => `${date} ${deal}\n`).join(''));
console.error(`${added} days added, from ${tried} deals tried`);
